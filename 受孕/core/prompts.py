def prompt_of(state: dict | None, group: str, key: str) -> str:
    return override(state, group, key) or default_of(group, key)


def set_prompt(state: dict, group: str, key: str, text: str) -> str:
    if group not in GROUPS or not any(k == key for k, _ in items(group)):
        return ""
    value = str(text or "").strip()[:PROMPT_MAX]
    box = _box(state)
    row = box.get(group)
    if not isinstance(row, dict):
        row = {}
        box[group] = row
    if not value or value == default_of(group, key):
        row.pop(key, None)
    else:
        row[key] = value
    if not row:
        box.pop(group, None)
    return prompt_of(state, group, key)


def set_many(state: dict, group: str, texts) -> int:
    """一次存一组；texts 是 {key: text}。返回改了/清掉的段数。"""
    if group not in GROUPS or not isinstance(texts, dict):
        return 0
    changed = 0
    for key, text in texts.items():
        if not any(k == key for k, _ in items(group)):
            continue
        before = prompt_of(state, group, key)
        after = set_prompt(state, group, key, str(text or ""))
        if before != after:
            changed += 1
    return changed


def reset(state: dict, group: str | None = None, key: str | None = None) -> int:
    box = _box(state)
    if group is None:
        count = sum(len(row) for row in box.values() if isinstance(row, dict))
        box.clear()
        return count
    row = box.get(group)
    if not isinstance(row, dict):
        return 0
    if key is None:
        count = len(row)
        box.pop(group, None)
        return count
    had = 1 if row.pop(key, None) else 0
    if not row:
        box.pop(group, None)
    return had


def payload(state: dict) -> list[dict]:
    result = []
    for group in groups():
        rows = []
        for key, label in items(group):
            default = default_of(group, key)
            custom = override(state, group, key)
            rows.append({
                "key": key,
                "label": label,
                "default": default,
                "value": custom or default,
                "custom": bool(custom),
            })
        result.append({
            "key": group,
            "label": group_label(group),
            "items": rows,
            "max_len": PROMPT_MAX,
            "custom_count": sum(1 for row in rows if row["custom"]),
        })
    return result


def text(state: dict | None, group: str, key: str, **fmt) -> str:
    """取一段提示词并替换占位符；没有就返回空。"""
    value = prompt_of(state, group, key)
    if not value:
        return ""
    for name, replacement in fmt.items():
        value = value.replace("{" + name + "}", str(replacement))
    return value
